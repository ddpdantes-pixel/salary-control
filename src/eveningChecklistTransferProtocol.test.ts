import { describe, expect, it } from 'vitest'
import { EVENING_CHECKLIST_TRANSFER_PROTOCOL } from './eveningChecklistTransferProtocol'

describe('канонический регламент переноса вечернего чек-листа', () => {
  it('сохраняет полный текст и ключевые правила без смысловых сокращений', () => {
    expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL.length).toBeGreaterThan(20_000)
    ;[
      'последние 7 календарных дней',
      '14 последних дней',
      'Не ограничивай историю 14 днями',
      'Сравнение тренировок обязательно',
      'Предыдущее выполнение этой тренировки',
      'Тренировки 2/3',
      'предыдущее подтверждённое состояние',
      'сегодняшние подтверждённые факты',
      'План не равен выполнению',
      'Текущая неделя',
      'Тренировки — X/3',
      'Речь — X/3',
      'Кавист — X/2',
      'Керамогранит — X/1',
      'Шампунь — X/3',
      'Миноксидил — X/7',
      'Алкоголь — X/2',
      'Безалкогольное пиво — X/2',
      'Чистые вечера — X/3',
      '22.08.2026',
      'Расслабление 14/14',
      'Ничего не додумывать',
      'Блок «Завтра» обязателен',
      '4–5 предложений максимум',
      'не буду придумывать',
      'именно этой программы',
    ].forEach((phrase) => expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL).toContain(phrase))
  })

  it('не возвращает старую трактовку любого вечернего напитка как безалкогольного пива', () => {
    expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL).toContain(
      'Под этим счётчиком понимать именно употребление безалкогольного пива.',
    )
    expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL).toContain(
      'Обычная газировка или другой напиток без алкоголя и без пива не отменяет статус чистого вечера.',
    )
    expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL).not.toContain(
      'безалкогольных вечеров с банкой / привычным вечерним напитком',
    )
    expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL).not.toContain(
      'обычная газировка относится к безалкогольному пиву',
    )
  })

  it('добавляет режим активного коуча после всего прежнего регламента', () => {
    const previousEnding = '«Завтра» — обязательно и коротко, 4–5 предложений.'
    const heading = 'РЕЖИМ АКТИВНОГО КОУЧА — ОБЯЗАТЕЛЬНО'
    const sectionStart = EVENING_CHECKLIST_TRANSFER_PROTOCOL.indexOf(heading)

    expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL).toContain(`${previousEnding}\n\n${heading}`)
    expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL.lastIndexOf(heading)).toBe(sectionStart)
    expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL.endsWith(
      'Главный принцип: не наблюдатель, а внимательный партнёр, который иногда говорит «нет, здесь я с тобой не согласен» и объясняет почему.',
    )).toBe(true)
  })

  it('сохраняет все обязательные правила режима активного коуча', () => {
    ;[
      'РЕЖИМ АКТИВНОГО КОУЧА — ОБЯЗАТЕЛЬНО',
      'Вечерний чек-лист — не пассивный отчёт и не пересказ данных.',
      'нельзя ограничиваться мягкими формулировками',
      'настойчиво рекомендовать следующий вечер без алкоголя',
      'предпочтительно также без безалкогольного пива',
      'обозначить ближайшую тренировку как приоритет',
      'требовать конкретного снижения на следующий день',
      'не соглашаться ради комфорта',
      'здоровье имеет приоритет над выполнением недельного счётчика',
      'нет, здесь я с тобой не согласен',
    ].forEach((phrase) => expect(EVENING_CHECKLIST_TRANSFER_PROTOCOL).toContain(phrase))
  })
})
